#include <assert.h>
#include <stdio.h>
#include <stdint.h>
#include <string.h>

#include "db_rtcm.h"

#define TEST_MAX_FRAMES 8U

/** Frames reported by the framer during one test. */
typedef struct {
    size_t count;
    uint16_t lengths[TEST_MAX_FRAMES];
    uint8_t frames[TEST_MAX_FRAMES][DB_RTCM3_MAX_FRAME_LEN];
} captured_t;

/**
 * Framer callback that stores every reported frame.
 *
 * @param frame Complete frame
 * @param frame_length Frame length
 * @param context captured_t to fill
 */
static void capture_frame(const uint8_t *frame, uint16_t frame_length, void *context) {
    captured_t *captured = (captured_t *) context;
    assert(captured->count < TEST_MAX_FRAMES);
    memcpy(captured->frames[captured->count], frame, frame_length);
    captured->lengths[captured->count] = frame_length;
    captured->count++;
}

/**
 * Builds a valid RTCM3 frame with the given message number and payload length.
 *
 * @param out Destination, room for DB_RTCM3_MAX_FRAME_LEN bytes
 * @param message_type 12 bit message number (ignored if payload_length < 2)
 * @param payload_length 0..1023
 * @param seed Varies the payload content
 * @return Frame length
 */
static uint16_t build_frame(uint8_t *out, uint16_t message_type, uint16_t payload_length, uint8_t seed) {
    out[0] = DB_RTCM3_PREAMBLE;
    out[1] = (uint8_t) ((payload_length >> 8) & 0x03U);
    out[2] = (uint8_t) (payload_length & 0xFFU);
    for (uint16_t i = 0; i < payload_length; i++) {
        out[3 + i] = (uint8_t) (seed + i * 7U);
    }
    if (payload_length >= 2) {
        out[3] = (uint8_t) (message_type >> 4);
        out[4] = (uint8_t) ((((unsigned int) message_type << 4) & 0xF0U) | (out[4] & 0x0FU));
    }
    const uint32_t crc = db_rtcm3_crc24q(out, 3U + payload_length);
    out[3 + payload_length] = (uint8_t) (crc >> 16);
    out[4 + payload_length] = (uint8_t) (crc >> 8);
    out[5 + payload_length] = (uint8_t) crc;
    return (uint16_t) (6U + payload_length);
}

/** CRC-24Q matches the standard check value and the real RTCM 1005 frame used on the bench. */
static void test_crc24q(void) {
    const uint8_t check[] = "123456789";
    assert(db_rtcm3_crc24q(check, 9) == 0xCDE703UL);
    assert(db_rtcm3_crc24q(NULL, 0) == 0);
    // RTCM 1005 frame generated by test/rtk_emulator.py and sent through the bench link
    const uint8_t f1005[] = {0xd3, 0x00, 0x13, 0x3e, 0xd0, 0x00, 0x03, 0x8a, 0x00, 0x0b, 0x18, 0x00, 0x02, 0x96, 0x23,
                             0x99, 0x50, 0x0a, 0xa2, 0x88, 0xfe, 0x80, 0x89, 0x0e, 0x49};
    assert(db_rtcm3_crc24q(f1005, sizeof(f1005) - 3) == 0x890E49UL);
    assert(db_rtcm3_message_type(f1005, sizeof(f1005)) == 1005);
}

/** One frame fed at once and fed byte by byte is reported exactly once and unchanged. */
static void test_framer_single_frame(void) {
    uint8_t frame[DB_RTCM3_MAX_FRAME_LEN];
    const uint16_t len = build_frame(frame, 1074, 150, 3);
    db_rtcm3_framer_t framer;
    captured_t captured = {0};

    db_rtcm3_framer_init(&framer);
    db_rtcm3_framer_feed(&framer, frame, len, capture_frame, &captured);
    assert(captured.count == 1 && captured.lengths[0] == len && memcmp(captured.frames[0], frame, len) == 0);
    assert(framer.frames == 1 && framer.skipped_bytes == 0 && framer.length == 0);

    memset(&captured, 0, sizeof(captured));
    db_rtcm3_framer_init(&framer);
    for (uint16_t i = 0; i < len; i++) {
        db_rtcm3_framer_feed(&framer, &frame[i], 1, capture_frame, &captured);
        assert(captured.count == (i + 1U == len ? 1U : 0U));
    }
    assert(memcmp(captured.frames[0], frame, len) == 0);
    assert(db_rtcm3_message_type(captured.frames[0], captured.lengths[0]) == 1074);
}

/** Back-to-back frames, the smallest (empty payload) and the largest frame, split across feeds. */
static void test_framer_sizes_and_splits(void) {
    uint8_t stream[3 * DB_RTCM3_MAX_FRAME_LEN];
    uint16_t lengths[3];
    lengths[0] = build_frame(stream, 0, 0, 1);
    lengths[1] = build_frame(&stream[lengths[0]], 1005, 19, 2);
    lengths[2] = build_frame(&stream[lengths[0] + lengths[1]], 4094, DB_RTCM3_MAX_PAYLOAD_LEN, 9);
    const size_t total = (size_t) lengths[0] + lengths[1] + lengths[2];
    assert(lengths[2] == DB_RTCM3_MAX_FRAME_LEN);

    for (size_t cut = 1; cut < total; cut += 97) {
        db_rtcm3_framer_t framer;
        captured_t captured = {0};
        db_rtcm3_framer_init(&framer);
        db_rtcm3_framer_feed(&framer, stream, cut, capture_frame, &captured);
        db_rtcm3_framer_feed(&framer, &stream[cut], total - cut, capture_frame, &captured);
        assert(captured.count == 3);
        size_t offset = 0;
        for (size_t i = 0; i < 3; i++) {
            assert(captured.lengths[i] == lengths[i]);
            assert(memcmp(captured.frames[i], &stream[offset], lengths[i]) == 0);
            offset += lengths[i];
        }
        assert(framer.skipped_bytes == 0 && framer.length == 0);
    }
}

/** Other protocols, false preambles and a corrupted frame are skipped; the next valid frame is still found. */
static void test_framer_resync(void) {
    uint8_t frame[DB_RTCM3_MAX_FRAME_LEN];
    const uint16_t len = build_frame(frame, 1124, 60, 5);
    uint8_t stream[64 + 2 * DB_RTCM3_MAX_FRAME_LEN];
    size_t n = 0;
    // UBX-like and NMEA-like noise without a preamble
    const uint8_t noise[] = {0xB5, 0x62, 0x01, 0x07, '$', 'G', 'N', 'G', 'G', 'A', '\r', '\n'};
    memcpy(&stream[n], noise, sizeof(noise));
    n += sizeof(noise);
    // false preamble with reserved bits set
    stream[n++] = DB_RTCM3_PREAMBLE;
    stream[n++] = 0xFF;
    // false preamble with a plausible header whose CRC will not match; the real frame starts inside its "payload"
    stream[n++] = DB_RTCM3_PREAMBLE;
    stream[n++] = 0x00;
    stream[n++] = 0x05;
    // corrupted copy of the frame (one payload byte flipped)
    memcpy(&stream[n], frame, len);
    stream[n + 10] ^= 0x40;
    n += len;
    // the valid frame
    memcpy(&stream[n], frame, len);
    n += len;

    db_rtcm3_framer_t framer;
    captured_t captured = {0};
    db_rtcm3_framer_init(&framer);
    db_rtcm3_framer_feed(&framer, stream, n, capture_frame, &captured);
    assert(captured.count == 1);
    assert(captured.lengths[0] == len && memcmp(captured.frames[0], frame, len) == 0);
    assert(framer.frames == 1);
    assert(framer.skipped_bytes == n - len);
    assert(framer.length == 0);

    // the same stream byte by byte gives the same result
    memset(&captured, 0, sizeof(captured));
    db_rtcm3_framer_init(&framer);
    for (size_t i = 0; i < n; i++) {
        db_rtcm3_framer_feed(&framer, &stream[i], 1, capture_frame, &captured);
    }
    assert(captured.count == 1 && memcmp(captured.frames[0], frame, len) == 0);
    assert(framer.skipped_bytes == n - len);
}

/** NULL arguments are ignored without crashing. */
static void test_framer_invalid_arguments(void) {
    db_rtcm3_framer_t framer;
    const uint8_t byte = DB_RTCM3_PREAMBLE;
    db_rtcm3_framer_init(NULL);
    db_rtcm3_framer_init(&framer);
    db_rtcm3_framer_feed(NULL, &byte, 1, NULL, NULL);
    db_rtcm3_framer_feed(&framer, NULL, 1, NULL, NULL);
    assert(framer.length == 0 && framer.frames == 0);
    db_rtcm3_framer_feed(&framer, &byte, 1, NULL, NULL);
    assert(framer.length == 1);
}

/** Expected part layout for representative frame sizes. */
static void test_split_layout(void) {
    uint8_t frame[DB_RTCM3_MAX_FRAME_LEN];
    for (uint16_t i = 0; i < sizeof(frame); i++) {
        frame[i] = (uint8_t) i;
    }
    db_rtcm_mav_part_t parts[DB_RTCM_MAV_MAX_PARTS];
    uint8_t seq = 5;

    // small: one unfragmented part, sequence untouched
    assert(db_rtcm_mav_split(frame, 25, &seq, parts) == 1);
    assert(parts[0].flags == 0 && parts[0].length == 25 && parts[0].data == frame && seq == 5);
    assert(db_rtcm_mav_split(frame, 180, &seq, parts) == 1);
    assert(parts[0].flags == 0 && parts[0].length == 180 && seq == 5);

    // 181: two fragments of sequence 5
    assert(db_rtcm_mav_split(frame, 181, &seq, parts) == 2);
    assert(parts[0].flags == (0x01 | (0 << 1) | (5 << 3)) && parts[0].length == 180);
    assert(parts[1].flags == (0x01 | (1 << 1) | (5 << 3)) && parts[1].length == 1 && parts[1].data == &frame[180]);
    assert(seq == 6);

    // 600: 180, 180, 180, 60 with sequence 6
    assert(db_rtcm_mav_split(frame, 600, &seq, parts) == 4);
    assert(parts[3].flags == (0x01 | (3 << 1) | (6 << 3)) && parts[3].length == 60);
    assert(seq == 7);

    // exact multiples below 720 need an empty last fragment
    assert(db_rtcm_mav_split(frame, 360, &seq, parts) == 3);
    assert(parts[2].length == 0 && parts[2].flags == (0x01 | (2 << 1) | (7 << 3)));
    assert(db_rtcm_mav_split(frame, 540, &seq, parts) == 4);
    assert(parts[3].length == 0 && parts[3].flags == (0x01 | (3 << 1) | (8 << 3)));

    // 720: four full fragments, no terminator
    assert(db_rtcm_mav_split(frame, 720, &seq, parts) == 4);
    assert(parts[3].length == 180 && seq == 10);

    // above 720: unfragmented chunks, sequence untouched
    assert(db_rtcm_mav_split(frame, 721, &seq, parts) == 5);
    assert(parts[4].flags == 0 && parts[4].length == 1 && seq == 10);
    assert(db_rtcm_mav_split(frame, DB_RTCM3_MAX_FRAME_LEN, &seq, parts) == DB_RTCM_MAV_MAX_PARTS);
    assert(parts[5].length == DB_RTCM3_MAX_FRAME_LEN - 5 * 180);

    // sequence wraps after 31 and only its low 5 bits are used
    seq = 31;
    assert(db_rtcm_mav_split(frame, 200, &seq, parts) == 2);
    assert((parts[0].flags >> 3) == 31 && seq == 0);
    seq = 0xE3;
    assert(db_rtcm_mav_split(frame, 200, &seq, parts) == 2);
    assert((parts[0].flags >> 3) == 3 && seq == 4);

    // invalid input
    seq = 9;
    assert(db_rtcm_mav_split(frame, 0, &seq, parts) == 0);
    assert(db_rtcm_mav_split(frame, DB_RTCM3_MAX_FRAME_LEN + 1, &seq, parts) == 0);
    assert(db_rtcm_mav_split(NULL, 10, &seq, parts) == 0);
    assert(db_rtcm_mav_split(frame, 10, NULL, parts) == 0);
    assert(db_rtcm_mav_split(frame, 10, &seq, NULL) == 0);
    assert(seq == 9);
}

/** Receiver state implementing the GPS_RTCM_DATA rules the way ArduPilot does, used to check the splitter. */
typedef struct {
    uint8_t buffer[DB_RTCM_MAV_DATA_LEN * DB_RTCM_MAV_MAX_FRAGMENTS];
    uint8_t sequence;
    uint8_t received;
    uint8_t count;
    uint16_t length;
} test_reassembler_t;

/**
 * Adds one GPS_RTCM_DATA message to the reference receiver and appends completed data to the output stream.
 *
 * @param r Receiver state
 * @param part Message content
 * @param out Output stream
 * @param out_length In/out: bytes in the output stream
 */
static void test_reassemble(test_reassembler_t *r, const db_rtcm_mav_part_t *part, uint8_t *out, size_t *out_length) {
    if ((part->flags & 0x01U) == 0) {
        memcpy(&out[*out_length], part->data, part->length);
        *out_length += part->length;
        return;
    }
    const uint8_t fragment = (part->flags >> 1) & 0x03U;
    const uint8_t sequence = (part->flags >> 3) & 0x1FU;
    if (r->received && (r->sequence != sequence || (r->received & (1U << fragment)))) {
        r->received = 0;
        r->count = 0;
    }
    r->sequence = sequence;
    r->received |= (uint8_t) (1U << fragment);
    memcpy(&r->buffer[DB_RTCM_MAV_DATA_LEN * fragment], part->data, part->length);
    if (part->length < DB_RTCM_MAV_DATA_LEN) {
        r->count = (uint8_t) (fragment + 1U);
        r->length = (uint16_t) (DB_RTCM_MAV_DATA_LEN * fragment + part->length);
    } else if (r->received == 0x0F) {
        r->count = DB_RTCM_MAV_MAX_FRAGMENTS;
        r->length = DB_RTCM_MAV_DATA_LEN * DB_RTCM_MAV_MAX_FRAGMENTS;
    }
    if (r->count != 0 && r->received == (uint8_t) ((1U << r->count) - 1U)) {
        memcpy(&out[*out_length], r->buffer, r->length);
        *out_length += r->length;
        r->received = 0;
        r->count = 0;
    }
}

/** Every frame size 1..1029 survives split + reference reassembly unchanged, also many frames in a row. */
static void test_split_roundtrip(void) {
    static uint8_t frame[DB_RTCM3_MAX_FRAME_LEN];
    static uint8_t out[DB_RTCM3_MAX_FRAME_LEN];
    test_reassembler_t receiver;
    memset(&receiver, 0, sizeof(receiver));
    uint8_t seq = 0;
    for (uint16_t len = 1; len <= DB_RTCM3_MAX_FRAME_LEN; len++) {
        for (uint16_t i = 0; i < len; i++) {
            frame[i] = (uint8_t) (len + i * 13U);
        }
        db_rtcm_mav_part_t parts[DB_RTCM_MAV_MAX_PARTS];
        const uint8_t n = db_rtcm_mav_split(frame, len, &seq, parts);
        assert(n >= 1 && n <= DB_RTCM_MAV_MAX_PARTS);
        size_t out_length = 0;
        for (uint8_t p = 0; p < n; p++) {
            assert(parts[p].length <= DB_RTCM_MAV_DATA_LEN);
            test_reassemble(&receiver, &parts[p], out, &out_length);
        }
        assert(out_length == len);
        assert(memcmp(out, frame, len) == 0);
    }
}

/**
 * Runs all RTCM helper tests.
 *
 * @return 0 when all assertions pass
 */
int main(void) {
    test_crc24q();
    test_framer_single_frame();
    test_framer_sizes_and_splits();
    test_framer_resync();
    test_framer_invalid_arguments();
    test_split_layout();
    test_split_roundtrip();
    printf("db_rtcm_test: all tests passed\n");
    return 0;
}
